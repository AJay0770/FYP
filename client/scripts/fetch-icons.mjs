const here = path.dirname(fileURLToPath(import.meta.url))
const outDir = path.join(here, '..', 'src', 'components', 'icons')

async function fetchText(url) {
  const res = await fetch(url, { redirect: 'follow' })
  if (!res.ok) throw new Error(`${res.status} for ${url}`)
  return res.text()
}

const data = {}
const missing = []
for (const name of Object.keys(ICONS)) {
  try {
    const svg = await fetchText(`${BASE}/icons/${name}.svg`)
    // Keep only the drawing elements; the wrapper <svg> is rendered by <Icon>.
    const inner = svg
      .replace(/<!--[\s\S]*?-->/g, '')
      .replace(/^[\s\S]*?<svg[^>]*>/, '')
      .replace(/<\/svg>\s*$/, '')
      .replace(/\s+/g, ' ')
      .trim()
    if (!inner) throw new Error('empty')
    data[name] = inner
  } catch (err) {
    missing.push(`${name} (${err.message})`)
  }
}

if (missing.length) {
  console.error(`Could not fetch: ${missing.join(', ')}`)
  process.exit(1)
}

await mkdir(outDir, { recursive: true })
const body = Object.entries(data)
  .map(([name, inner]) => `  '${name}': '${inner.replace(/'/g, "\\'")}',`)
  .join('\n')
await writeFile(
  path.join(outDir, 'iconData.js'),
  `// GENERATED by scripts/fetch-icons.mjs from lucide-static@${VERSION} - do not edit by hand.\n` +
    `// Lucide icons are ISC licensed; see LICENSE-lucide.txt in this folder.\n` +
    `export default {\n${body}\n}\n`
)
await writeFile(path.join(outDir, 'LICENSE-lucide.txt'), await fetchText(`${BASE}/LICENSE`))
console.log(`Wrote ${Object.keys(data).length} icons from lucide-static@${VERSION}`)
